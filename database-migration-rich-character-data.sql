-- Add richer character details without deleting existing character records.
ALTER TABLE characters
  ADD COLUMN IF NOT EXISTS real_name TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS alias TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS origin TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS alignment TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS first_appearance TEXT NOT NULL DEFAULT '';

-- Powers and teams are reusable across many characters, so they have their own tables.
CREATE TABLE IF NOT EXISTS powers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- These join tables allow each character to have several powers and teams,
-- and each power or team to be shared by multiple characters.
CREATE TABLE IF NOT EXISTS character_powers (
  character_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  power_id BIGINT NOT NULL REFERENCES powers(id) ON DELETE CASCADE,
  PRIMARY KEY (character_id, power_id)
);

CREATE TABLE IF NOT EXISTS character_teams (
  character_id BIGINT NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  PRIMARY KEY (character_id, team_id)
);

CREATE INDEX IF NOT EXISTS character_powers_power_id_idx ON character_powers (power_id);
CREATE INDEX IF NOT EXISTS character_teams_team_id_idx ON character_teams (team_id);

ALTER TABLE public.characters ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.powers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.character_powers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.character_teams ENABLE ROW LEVEL SECURITY;
